#!/usr/bin/env node
/**
 * three's GLSL to TSL transpiler on the GLSL of one real patch, `godotLightFunction.ts`: first the
 * text as the patch holds it, then the text with what the transpiler refuses resolved by hand.
 *   node scripts/tsl-spike/transpile.mjs [--write scripts/tsl-spike/lab/generated/lightFunctions.js]
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import GLSLDecoder from 'three/addons/transpiler/GLSLDecoder.js';
import Transpiler from 'three/addons/transpiler/Transpiler.js';
import TSLEncoder from 'three/addons/transpiler/TSLEncoder.js';
import { REPO_ROOT } from '../visual/previewServer.mjs';

const PATCH = 'packages/textscene-core/src/r3f/godotLightFunction.ts';

/** The GLSL of the template literal `name` holds in the patch's source. */
function glslOf(source, name) {
  const found = new RegExp(`const ${name} = /\\* glsl \\*/ \`([\\s\\S]*?)\`;`).exec(source);
  if (!found) throw new Error(`expected a GLSL constant ${name} in ${PATCH}, found none`);
  return found[1];
}

/** Keeps the branch of each conditional that the default material compiles: the one with no define. */
function defaultBranches(glsl) {
  const kept = [];
  const taking = [];
  for (const line of glsl.split('\n')) {
    const directive = /^\s*#\s*(if|ifdef|elif|else|endif)\b/.exec(line)?.[1];
    if (directive === 'if' || directive === 'ifdef') taking.push(false);
    else if (directive === 'elif') taking[taking.length - 1] = false;
    else if (directive === 'else') taking[taking.length - 1] = true;
    else if (directive === 'endif') taking.pop();
    else if (taking.every(Boolean)) kept.push(line);
  }
  return kept.join('\n');
}

/** three's chunk helpers and material struct, written out as the transpiler needs them. */
function withoutChunkHelpers(glsl) {
  return glsl
    .replaceAll('RECIPROCAL_PI', '0.3183098861837907')
    .replace(/saturate\(/g, 'clamp01(')
    .replace(/pow2\( material\.godotRoughness \)/g, '( roughness * roughness )')
    .replace(
      'const in PhysicalMaterial material, ',
      'const in vec3 f0, const in float metalness, const in float roughness, '
    )
    .replace('vec3 f0 = material.specularColorBlended;\n', '')
    .replace('material.metalness', 'metalness')
    .replace(/\/\/.*$/gm, '');
}

const CLAMP01 = 'float clamp01( const in float x ) { return clamp( x, 0.0, 1.0 ); }\n';

function transpile(glsl) {
  try {
    return { tsl: new Transpiler(new GLSLDecoder(), new TSLEncoder()).parse(glsl) };
  } catch (error) {
    return { error: String(error?.message ?? error) };
  }
}

const source = readFileSync(resolve(REPO_ROOT, PATCH), 'utf8');
const asWritten = glslOf(source, 'DIFFUSE_NL') + glslOf(source, 'SPECULAR_BRDF');
const verbatim = transpile(asWritten);
console.log(`as the patch holds it: ${verbatim.error ? `fails, ${verbatim.error}` : 'transpiles'}`);

const prepared = CLAMP01 + withoutChunkHelpers(defaultBranches(asWritten));
const result = transpile(prepared);
console.log(
  `with the default branches and no chunk helper: ${result.error ? `fails, ${result.error}` : 'transpiles'}`
);

const writeIndex = process.argv.indexOf('--write');
if (result.tsl && writeIndex !== -1) {
  const out = resolve(process.argv[writeIndex + 1]);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `// GENERATED by scripts/tsl-spike/transpile.mjs from ${PATCH}.\n${result.tsl}\n`);
  console.log(`wrote ${out}`);
} else if (result.tsl) {
  console.log(result.tsl);
}
