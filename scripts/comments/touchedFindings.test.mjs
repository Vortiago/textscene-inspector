import { describe, expect, it } from 'vitest';
import { isCheckedSource, touchedFindings } from './touchedFindings.mjs';

const PRINT_WIDTH = 40;
const TEXT =
  'const a = 1;\n// Old, kept as it was,\n// over two lines.\nconst b = 2;\n// New,\n// over two.\n';

function rulesAt(text, added) {
  return touchedFindings(text, 'file.ts', added, PRINT_WIDTH).map(({ line, rule }) => ({ line, rule }));
}

describe('touchedFindings', () => {
  it('reports a comment that holds an added line', () => {
    expect(rulesAt(TEXT, new Set([6]))).toEqual([{ line: 5, rule: 'long-comment' }]);
  });

  it('leaves a comment with no added line, so an old one stands until it is touched', () => {
    expect(rulesAt(TEXT, new Set([4]))).toEqual([]);
  });

  it('reports every comment of a file it reads whole', () => {
    expect(rulesAt(TEXT, 'all').map(({ line }) => line)).toEqual([2, 5]);
  });

  it('reports nothing for a generated file', () => {
    expect(rulesAt(`// GENERATED by a script.\n${TEXT}`, 'all')).toEqual([]);
  });
});

describe('isCheckedSource', () => {
  it('checks a script or a TypeScript source', () => {
    expect(['a.ts', 'b.tsx', 'c.js', 'd.mjs', 'e.cjs', 'f.jsx'].every(isCheckedSource)).toBe(true);
  });

  it('skips a generated or a vendored source and other files', () => {
    const paths = ['a.generated.ts', 'scripts/compare-docs/vendor/gifenc.mjs', 'README.md', 'a.d.ts.map'];
    expect(paths.some(isCheckedSource)).toBe(false);
  });
});
