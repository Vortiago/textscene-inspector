#!/usr/bin/env node
/**
 * Writes the template files of Godot's renderer and the mode table of each shader type from
 * Godot's source (scripts/godotSource.mjs): `pnpm godot:templates [--check] [--godot-source <dir>]`.
 * The templates are bundled unchanged. `--check` writes nothing and exits 1 on a stale file.
 */

import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { checkGenerated, writeGenerated } from '../generatedFile.mjs';
import { godotSourceDir } from '../godotSource.mjs';
import { godotVersion } from '../godot-shader-language/readSource.mjs';
import { REPO_ROOT } from '../repoRoot.mjs';
import { MODE_TABLE_SOURCES, modeTable } from './modeTables.mjs';

export const TEMPLATE_DIR = 'servers/rendering/renderer_rd/shaders';
const OUT_DIR = join(REPO_ROOT, 'packages/textscene-core/src/shaders/template');

/**
 * The FSR templates include AMD's FidelityFX code from `thirdparty/`, which the CI image leaves
 * out. They join with the slice that ports FSR.
 */
export const WAITS_FOR_FSR = /(^|\/)fsr/;

const LICENCE = ` * Godot Engine (MIT).
 * Copyright (c) 2014-present Godot Engine contributors.
 * Copyright (c) 2007-2014 Juan Linietsky, Ariel Manzur.
 * See THIRD-PARTY-NOTICES.md.`;

/** Every `.glsl` file under `dir`, by its path from `dir`, sorted. */
export function glslFiles(dir) {
  const files = [];
  const walk = (at) => {
    for (const name of readdirSync(at)) {
      const path = join(at, name);
      if (statSync(path).isDirectory()) walk(path);
      else if (name.endsWith('.glsl')) files.push(relative(dir, path));
    }
  };
  walk(dir);
  return files.sort();
}

function renderTemplates(godotDir, version) {
  const dir = join(godotDir, TEMPLATE_DIR);
  const entries = glslFiles(dir)
    .filter((file) => !WAITS_FOR_FSR.test(file))
    .map((file) => `  ${JSON.stringify(file)}: ${JSON.stringify(readFileSync(join(dir, file), 'utf8'))},`);
  return `/**
 * GENERATED by \`pnpm godot:templates\` from Godot ${version}'s \`${TEMPLATE_DIR}/\`. Do not edit.
 * The template files of Godot's renderer, unchanged, by their path under that directory.
${LICENCE}
 */

export const TEMPLATE_FILES: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`;
}

function renderModeTables(godotDir, version) {
  const tables = Object.entries(MODE_TABLE_SOURCES).map(([type, file]) => {
    const table = modeTable(readFileSync(join(godotDir, 'servers/rendering', file), 'utf8'), file);
    return `  // servers/rendering/${file}\n  ${type}: ${JSON.stringify(table, null, 2).replaceAll('\n', '\n  ')},`;
  });
  return `/**
 * GENERATED by \`pnpm godot:templates\` from Godot ${version}'s C++. Do not edit.
 * The mode table of each shader type: the \`DefaultIdentifierActions\` its renderer gives
 * \`ShaderCompiler::initialize\`, at the default project settings.
${LICENCE}
 */

import type { ModeTable } from './modeTable.js';

export const MODE_TABLES: Readonly<Record<string, ModeTable>> = {
${tables.join('\n')}
};
`;
}

function main() {
  const godotDir = godotSourceDir(process.argv);
  const version = godotVersion(readFileSync(join(godotDir, 'version.py'), 'utf8'));
  const outputs = [
    [join(OUT_DIR, 'templateFiles.generated.ts'), renderTemplates(godotDir, version)],
    [join(OUT_DIR, 'modeTables.generated.ts'), renderModeTables(godotDir, version)],
  ];
  const options = { tool: 'godot-templates' };
  if (process.argv.includes('--check'))
    checkGenerated(outputs, { ...options, command: 'pnpm godot:templates' });
  else writeGenerated(outputs, options);
}

// `pathToFileURL`, not a `file://` template: on Windows `process.argv[1]` is a `C:\...` path.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
