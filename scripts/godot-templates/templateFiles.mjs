#!/usr/bin/env node
/**
 * Writes the template files of Godot's renderer, unchanged, from Godot's source
 * (scripts/godotSource.mjs): `node scripts/godot-templates/templateFiles.mjs [--godot-source <dir>]`.
 * The repository holds no copy. The install writes the file from the source, or a job outside the
 * CI image downloads the one its `godot-templates` job wrote. With neither, the install fails.
 */

import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { writeGenerated } from '../generatedFile.mjs';
import { foundGodotSourceDir } from '../godotSource.mjs';
import { godotVersion } from '../godot-shader-language/readSource.mjs';
import { REPO_ROOT } from '../repoRoot.mjs';

export const TEMPLATE_DIR = 'servers/rendering/renderer_rd/shaders';

/** The file the transpiler's link step reads, in core's source. Git ignores it. */
export const TEMPLATE_FILES_PATH = join(
  REPO_ROOT,
  'packages/textscene-core/src/shaders/template/templateFiles.generated.ts'
);

/**
 * The FSR templates include AMD's FidelityFX code from `thirdparty/`, which the CI image leaves
 * out. They join with the slice that ports FSR.
 */
export const WAITS_FOR_FSR = /(^|\/)fsr/;

export const GODOT_LICENCE = ` * Godot Engine (MIT).
 * Copyright (c) 2014-present Godot Engine contributors.
 * Copyright (c) 2007-2014 Juan Linietsky, Ariel Manzur.
 * See THIRD-PARTY-NOTICES.md.`;

/** Every `.glsl` file under `dir`, by its path from `dir`, sorted. */
export function glslFiles(dir) {
  const files = [];
  const walk = (at) => {
    for (const name of readdirSync(at)) {
      const path = join(at, name);
      if (statSync(path).isDirectory()) walk(path);
      else if (name.endsWith('.glsl')) files.push(relative(dir, path));
    }
  };
  walk(dir);
  return files.sort();
}

/** The module text that holds every template file of Godot's tree at `godotDir`. */
export function renderTemplateFiles(godotDir) {
  const version = godotVersion(readFileSync(join(godotDir, 'version.py'), 'utf8'));
  const dir = join(godotDir, TEMPLATE_DIR);
  const entries = glslFiles(dir)
    .filter((file) => !WAITS_FOR_FSR.test(file))
    .map((file) => `  ${JSON.stringify(file)}: ${JSON.stringify(readFileSync(join(dir, file), 'utf8'))},`);
  return `/**
 * GENERATED by \`scripts/godot-templates/templateFiles.mjs\` from Godot ${version}'s \`${TEMPLATE_DIR}/\`. Do not edit.
 * The template files of Godot's renderer, unchanged, by their path under that directory.
${GODOT_LICENCE}
 */

export const TEMPLATE_FILES: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`;
}

/**
 * Writes the file from Godot's source when `argv` finds it. Keeps a file a job downloaded when it
 * does not. Throws, naming both ways, when there is neither.
 */
export function writeTemplateFiles(argv) {
  const godotDir = foundGodotSourceDir(argv);
  if (godotDir) {
    writeGenerated([[TEMPLATE_FILES_PATH, renderTemplateFiles(godotDir)]], { tool: 'godot-template-files' });
    return;
  }
  if (existsSync(TEMPLATE_FILES_PATH)) {
    console.log('[godot-template-files] kept the file a job downloaded, as no Godot source is here.');
    return;
  }
  throw new Error(
    `expected Godot's source or ${relative(REPO_ROOT, TEMPLATE_FILES_PATH)}, found neither. The ` +
      "shader transpiler reads Godot's template files, which the repository does not hold. Run in " +
      'the CI image, pass --godot-source <dir> to this script, or download the godot-template-files ' +
      "artifact of a CI run into the file's folder."
  );
}

// `pathToFileURL`, not a `file://` template: on Windows `process.argv[1]` is a `C:\...` path.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeTemplateFiles(process.argv);
}
