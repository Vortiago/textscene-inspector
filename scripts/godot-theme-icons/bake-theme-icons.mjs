#!/usr/bin/env node
/**
 * Bakes Godot 4.6.3's own raster of each vendored default-theme icon into the committed
 * `themeIconRasters.generated.ts`: `pnpm godot:theme-icons`. Godot rasterises its SVG icons with
 * ThorVG and no browser raster matches the rim, so the previewer draws these PNGs at theme scale 1.
 * The bake needs the Godot binary (`GODOT_BIN`, else `godot`) and refuses any version but 4.6.3.
 * CI does not run it: `themeIconSource.test.ts` checks the committed module against the icon tables.
 */

import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { writeGenerated } from '../generatedFile.mjs';
import { REPO_ROOT } from '../repoRoot.mjs';

const GODOT_VERSION = '4.6.3';
const SRC = join(REPO_ROOT, 'packages/textscene-core/src');
const OUT = join(SRC, 'r3f/controls/native/themeIconRasters.generated.ts');

/** The modules whose `vendoredIcon(...)` calls the bake reads. */
const ICON_MODULES = [
  'r3f/controls/native/themeIcons.ts',
  'nodes/2d/ui/graphelement/graphIcons.ts',
  'nodes/2d/ui/lineedit/icons.ts',
  'nodes/2d/ui/spinbox/icons.ts',
];

/** Throws unless `versionOutput` (`godot --version`) is the 4.6.3 release. */
export function assertGodotVersion(versionOutput) {
  if (!versionOutput.startsWith(`${GODOT_VERSION}.`)) {
    throw new Error(`expected Godot ${GODOT_VERSION}, got ${versionOutput}`);
  }
}

/** Each icon key of a module's `vendoredIcon('key', NAME_B64)` calls with the base64 of its SVG. */
export function vendoredIconsOfSource(source) {
  const base64ByName = new Map(
    [...source.matchAll(/const (\w+_B64) =\s*'([^']+)'/g)].map((match) => [match[1], match[2]])
  );
  return [...source.matchAll(/vendoredIcon\(\s*'(\w+)',\s*(\w+_B64)\s*\)/g)].map((match) => {
    const base64 = base64ByName.get(match[2]);
    if (base64 === undefined) throw new Error(`expected a const ${match[2]} for the icon ${match[1]}`);
    return [match[1], base64];
  });
}

/** The generated module text: a PNG `data:` URL for each key, in key order. */
export function renderRasterModule(pngByKey, godotVersion) {
  const entries = Object.keys(pngByKey)
    .sort()
    .map((key) => `  ${key}: 'data:image/png;base64,${Buffer.from(pngByKey[key]).toString('base64')}',\n`);
  return `// GENERATED by scripts/godot-theme-icons/bake-theme-icons.mjs from Godot ${godotVersion}. Do not edit.

/**
 * Godot's own ThorVG raster of each vendored default-theme icon at theme scale 1, keyed as
 * \`vendoredIcon\` keys them. Licence: Godot Engine, MIT, see THIRD-PARTY-NOTICES.md.
 */
export const THEME_ICON_RASTERS: Readonly<Record<string, string>> = {
${entries.join('')}};
`;
}

function iconsOfModules() {
  const icons = new Map();
  for (const module of ICON_MODULES) {
    for (const [key, base64] of vendoredIconsOfSource(readFileSync(join(SRC, module), 'utf8'))) {
      icons.set(key, base64);
    }
  }
  return icons;
}

/** The PNG bytes of each icon key, rasterised by Godot in a scratch project. */
function rasterise(godot, icons) {
  const project = mkdtempSync(join(tmpdir(), 'theme-icons-'));
  try {
    mkdirSync(join(project, 'svg'));
    mkdirSync(join(project, 'png'));
    writeFileSync(join(project, 'project.godot'), 'config_version=5\n');
    for (const [key, base64] of icons) {
      writeFileSync(join(project, 'svg', `${key}.svg`), Buffer.from(base64, 'base64'));
    }
    const script = join(REPO_ROOT, 'scripts/godot-theme-icons/dump-rasters.gd');
    execFileSync(godot, ['--headless', '--path', project, '-s', script], { stdio: 'inherit' });
    return Object.fromEntries(
      readdirSync(join(project, 'png')).map((file) => [
        file.replace(/\.png$/, ''),
        readFileSync(join(project, 'png', file)),
      ])
    );
  } finally {
    rmSync(project, { recursive: true, force: true });
  }
}

function bake() {
  const godot = process.env.GODOT_BIN ?? 'godot';
  assertGodotVersion(execFileSync(godot, ['--version'], { encoding: 'utf8' }).trim());
  const rasters = rasterise(godot, iconsOfModules());
  writeGenerated([[OUT, renderRasterModule(rasters, GODOT_VERSION)]], { tool: 'godot-theme-icons' });
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    bake();
  } catch (error) {
    console.error(`[godot-theme-icons] ${error.message}`);
    process.exitCode = 1;
  }
}
