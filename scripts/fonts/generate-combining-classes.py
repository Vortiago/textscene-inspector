#!/usr/bin/env python3
"""Writes combiningClasses.ts: the combining class of each non-spacing mark that a canonical
decomposition ends in, as runs. Under --check, writes nothing and fails when the file is stale.
Run: pnpm fonts:combining-classes [--check]"""
import argparse
import sys
import unicodedata as u
from pathlib import Path

# Python, not Node: Node has no API for the canonical combining class. Each Python release pins
# one Unicode version (3.13 has 15.1.0), so another version fails rather than rewrite the table.
UNICODE_VERSION = "15.1.0"
TOOL = "combining-classes"
COMMAND = "pnpm fonts:combining-classes"
OUT_IN_REPO = "packages/textscene-core/src/r3f/controls/native/text/combiningClasses.ts"


def find_repo_root(start):
    """The nearest directory above `start` that holds pnpm-workspace.yaml, as scripts/repoRoot.mjs finds it."""
    for directory in [start, *start.parents]:
        if (directory / "pnpm-workspace.yaml").exists():
            return directory
    raise SystemExit(f"[{TOOL}] repo root (pnpm-workspace.yaml) not found above {start}")


def decomposed_marks():
    """Each non-spacing mark with a non-zero class that follows the first character of an NFD."""
    return sorted({ord(ch) for cp in range(0x110000) for ch in u.normalize("NFD", chr(cp))[1:]
                   if u.category(ch) == "Mn" and u.combining(ch)})


def class_runs(marks):
    """`[first, last, class]` runs of consecutive code points that share a class."""
    runs = []
    for cp in marks:
        klass = u.combining(chr(cp))
        if runs and runs[-1][1] == cp - 1 and runs[-1][2] == klass:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp, klass])
    return runs


def render(runs):
    # Lower-case hex digits: Prettier prints a number literal that way, and --check reads the file as Prettier left it.
    lines = "\n".join(f"  [0x{a:04x}, 0x{b:04x}, {k}]," for a, b, k in runs)
    return f"""// GENERATED by scripts/fonts/generate-combining-classes.py from Unicode {UNICODE_VERSION}. Do not edit.

/**
 * The combining class of each non-spacing mark that a canonical decomposition ends in, as runs of
 * `[first code point, last code point, class]` in ascending order.
 */
export const COMBINING_CLASS_RUNS: readonly (readonly [number, number, number])[] = [
{lines}
];
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="write nothing, fail when the file is stale")
    is_check = parser.parse_args().check
    if u.unidata_version != UNICODE_VERSION:
        sys.exit(f"[{TOOL}] expected Unicode {UNICODE_VERSION}, got {u.unidata_version} from Python "
                 f"{sys.version.split()[0]}: run it with Python 3.13")
    out = find_repo_root(Path(__file__).resolve().parent) / OUT_IN_REPO
    text = render(class_runs(decomposed_marks()))
    actual = out.read_text(encoding="utf-8") if out.exists() else None
    if actual == text:
        print(f"[{TOOL}] up to date.")
    elif is_check:
        sys.exit(f"[{TOOL}] 1 file(s) are STALE, run `{COMMAND}`:\n  {OUT_IN_REPO}")
    else:
        out.write_text(text, encoding="utf-8")
        print(f"[{TOOL}] wrote 1 file(s):\n  {OUT_IN_REPO}")


if __name__ == "__main__":
    main()
